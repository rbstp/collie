// Writes Linux/CollieTray/Printable.js: Quickshell's JS has no \p{} classes.
import { writeFileSync } from "node:fs";

const escaped =
  /[\p{Cc}\p{Cf}\p{Zl}\p{Zp}\p{Co}\p{Cs}\p{Cn}\p{Grapheme_Extend}\p{Default_Ignorable_Code_Point}]|[^\P{Zs} ]/u;
const ranges = [];
let start = -1;
for (let cp = 0; cp <= 0x110000; cp++) {
  const e = cp < 0x110000 && escaped.test(String.fromCodePoint(cp));
  if (e && start < 0) start = cp;
  if (!e && start >= 0) {
    ranges.push(start, cp - 1);
    start = -1;
  }
}
const rows = [];
for (let i = 0; i < ranges.length; i += 16) rows.push("  " + ranges.slice(i, i + 16).join(", "));
writeFileSync(
  new URL("../CollieTray/Printable.js", import.meta.url),
  `// Generated by Linux/Tests/gen-printable.mjs from Unicode ${process.versions.unicode}; do not edit.
// collied::printable and CollieBar's printable: phone strings with control, format, separator,
// private use, unassigned, combining and default ignorable characters escaped as \\u{...}.

var RANGES = [
${rows.join(",\n")}
]

function escaped(cp) {
  var lo = 0
  var hi = RANGES.length / 2 - 1
  while (lo <= hi) {
    var mid = (lo + hi) >> 1
    if (cp < RANGES[2 * mid]) hi = mid - 1
    else if (cp > RANGES[2 * mid + 1]) lo = mid + 1
    else return true
  }
  return false
}

function printable(s) {
  var out = ""
  for (const ch of String(s)) {
    var cp = ch.codePointAt(0)
    if (cp === 0) out += "\\\\0"
    else if (cp === 9) out += "\\\\t"
    else if (cp === 10) out += "\\\\n"
    else if (cp === 13) out += "\\\\r"
    else if (escaped(cp)) out += "\\\\u{" + cp.toString(16) + "}"
    else out += ch
  }
  return out
}

if (typeof module !== "undefined") module.exports = { printable: printable }
`,
);
