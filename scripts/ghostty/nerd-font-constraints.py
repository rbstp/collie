#!/usr/bin/env python3
# Writes Collie/GhosttyTerminal/Sources/GhosttyTerminal/NerdFontConstraints.swift from Ghostty's
# src/font/nerd_font_tables.zig at the commit scripts/ghostty/build-xcframework.sh pins.
import re
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "Collie/GhosttyTerminal/Sources/GhosttyTerminal/NerdFontConstraints.swift"

commit = re.search(r"^GHOSTTY_COMMIT=(\w+)", (ROOT / "scripts/ghostty/build-xcframework.sh").read_text(), re.M)[1]
url = f"https://raw.githubusercontent.com/ghostty-org/ghostty/{commit}/src/font/nerd_font_tables.zig"
zig = urllib.request.urlopen(url).read().decode()

stage1 = [int(v) for v in re.search(r"stage1: \[\d+\]u16 = \.\{([^}]*)\}", zig)[1].split(",")]
stage2 = [int(v) for v in re.search(r"stage2: \[\d+\]u16 = \.\{([^}]*)\}", zig)[1].split(",")]
body = zig[zig.index("pub const stage3"):]
literals = re.findall(r"null|\.\{[^{}]*\}", body[body.index("{") + 1:])

ranges = []
for cp in range(0x110000):
    index = stage2[stage1[cp >> 8] + (cp & 0xFF)] if stage1[cp >> 8] else 0
    if not index:
        continue
    if ranges and ranges[-1][1] == cp - 1 and ranges[-1][2] == index:
        ranges[-1][1] = cp
    else:
        ranges.append([cp, cp, index])

# Field order of NerdConstraint's memberwise initializer.
FIELDS = [
    ("size", "size"), ("height", "iconHeight"), ("max_constraint_width", "maxConstraintWidth"),
    ("align_horizontal", "alignHorizontal"), ("align_vertical", "alignVertical"),
    ("pad_top", "padTop"), ("pad_left", "padLeft"), ("pad_right", "padRight"), ("pad_bottom", "padBottom"),
    ("relative_width", "relativeWidth"), ("relative_height", "relativeHeight"),
    ("relative_x", "relativeX"), ("relative_y", "relativeY"), ("max_xy_ratio", "maxXYRatio"),
]
CASES = {".fit_cover1": ".fitCover1"}


def swift(literal):
    values = dict(re.findall(r"\.(\w+) = ([^,]+),", literal))
    args = []
    for zig_name, name in FIELDS:
        if zig_name not in values:
            continue
        value = values[zig_name]
        if zig_name == "height":
            value = "true" if value == ".icon" else "false"
        elif value.startswith("."):
            value = CASES.get(value, value)
        else:
            value = repr(float(value)) if "." in value or "e" in value else value
        args.append(f"{name}: {value}")
    return f"        NerdConstraint({', '.join(args)}),"


used = sorted({index for _, _, index in ranges})
position = {index: n for n, index in enumerate(used)}
rows = [", ".join(f"0x{lo:X}, 0x{hi:X}, {position[index]}" for lo, hi, index in ranges[i:i + 4])
        for i in range(0, len(ranges), 4)]
OUT.write_text(f"""// Generated by scripts/ghostty/nerd-font-constraints.py from src/font/nerd_font_tables.zig at Ghostty
// {commit}. Do not edit.

extension NerdConstraint {{
    /// Triples of first code point, last code point and index into `all`, sorted and disjoint.
    static let ranges: [UInt32] = [
{chr(10).join(f"        {row}," for row in rows)}
    ]

    static let all: [NerdConstraint] = [
{chr(10).join(swift(literals[index]) for index in used)}
    ]
}}
""")
print(f"{OUT.relative_to(ROOT)}: {len(ranges)} ranges, {len(used)} constraints")
